#!/usr/bin/env python3
"""Find repeated content inside each Long After chapter (the expansion passes can restate what a chapter already says).

For every chapter, compares each section with every other section and reports pairs that share
  - three or more identical 6-word runs, or
  - a sentence-level overlap (Jaccard >= 0.6 on content words) between any two sentences.
Writes content/longafter-v2/DUPES.md; prints the worst chapters. Exit 0 always (it's a reading list, not a gate).
"""
import re, glob, collections
from pathlib import Path

D = Path(__file__).resolve().parents[1] / "content/longafter-v2"
STOP = set("a an the to of in on and or is it you your for with that this be are as at if do not can it's they them their from by about".split())


def toks(s):
    return [w for w in re.findall(r"[a-z']+", re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", s.lower()))]


def grams(ws, n=6):
    return {" ".join(ws[i:i + n]) for i in range(len(ws) - n + 1)}


out, worst = ["# Repeated content inside chapters", "", "Generated by `scripts/longafter-dupes.py`. Each pair is a reading lead: merge, cut or keep.", ""], []
for f in sorted(glob.glob(str(D / "[0-9]*.md"))):
    for blk in re.split(r"^=== ", open(f).read(), flags=re.M)[1:]:
        slug = blk.split("\n", 1)[0].strip()
        body = blk.split("\n---\n", 1)[1].split("\n## Sources")[0]
        secs = [("(opening)", body.split("\n## ")[0])] + [(s.split("\n", 1)[0], s.split("\n", 1)[1] if "\n" in s else "") for s in re.split(r"^## ", body, flags=re.M)[1:]]
        hits = []
        for i in range(len(secs)):
            for j in range(i + 1, len(secs)):
                a, b = secs[i], secs[j]
                g = grams(toks(a[1])) & grams(toks(b[1]))
                sa = [set(toks(x)) - STOP for x in re.split(r"(?<=[.!?])\s+", a[1]) if len(x.split()) > 5]
                sb = [set(toks(x)) - STOP for x in re.split(r"(?<=[.!?])\s+", b[1]) if len(x.split()) > 5]
                close = sum(1 for x in sa for y in sb if x and y and len(x & y) / len(x | y) >= 0.6)
                if len(g) >= 3 or close >= 1:
                    hits.append((len(g) + close * 3, a[0], b[0], len(g), close))
        if hits:
            hits.sort(reverse=True)
            worst.append((sum(h[0] for h in hits), slug, len(hits)))
            out.append(f"## {slug}")
            out += [f"- \"{a}\" ↔ \"{b}\": {g} shared 6-word runs, {c} near-identical sentences" for _, a, b, g, c in hits]
            out.append("")
(D / "DUPES.md").write_text("\n".join(out) + "\n")
worst.sort(reverse=True)
print(f"{len(worst)} chapters with repeated content; worst:")
for s, slug, n in worst[:25]:
    print(f"  {s:4} {slug} ({n} pairs)")
