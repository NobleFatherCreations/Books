#!/usr/bin/env python3
"""Running checklist for The Long After expansion (owner request 2026-11-22).

Keeps two files in step:
  content/longafter-v2/progress.json   machine-readable (phases, per-part status, per-chapter words vs baseline, change log)
  content/longafter-v2/CHECKLIST.md    the same, readable

Usage
  python3 scripts/longafter-progress.py                       refresh word counts and re-render
  python3 scripts/longafter-progress.py --baseline            record today's words per chapter as the baseline (once)
  python3 scripts/longafter-progress.py --part i --status written --note "what changed"
  python3 scripts/longafter-progress.py --phase outline --status done --note "..."
"""
import argparse, datetime, glob, json, re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
D = ROOT / "content/longafter-v2"
PJ, MD = D / "progress.json", D / "CHECKLIST.md"
PHASES = [
    ("outline", "1. Expansion outline: every chapter, what a reader still needs (EXPANSION-OUTLINE.md)"),
    ("write", "2. Write the expansion, part by part (target: about 105,000 words, roughly double)"),
    ("voice", "3. Voice audit: every page read against the voice spec (BOOK-MAP-v2.md section 2), scored, weak passages rewritten"),
    ("slop", "4. No-AI-slop pass on the whole expanded book"),
    ("steelman", "5. Steelman of the finished book: hostile readers, gaps filled"),
    ("facts", "6. Fact check of everything new (FACTS.md)"),
    ("audit", "7. Full content audit + pipeline (scripts/longafter-pipeline.sh --fast)"),
    ("design", "8. Design work (only after 1-7 are done)"),
    ("deploy", "9. Deploy, on the owner's words only"),
]
PART_STEPS = ["outlined", "written", "audited"]


def words():
    out = {}
    for f in sorted(glob.glob(str(D / "[0-9]*.md"))):
        for blk in re.split(r"^=== ", open(f).read(), flags=re.M)[1:]:
            slug = blk.split("\n", 1)[0].strip()
            body = blk.split("\n---\n", 1)[1].split("\n## Sources")[0]
            out[slug] = len(re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", body).split())
    return out


def load():
    if PJ.exists():
        return json.load(open(PJ))
    plan = json.load(open(D / "plan.json"))
    return {"started": str(datetime.date.today()), "target_words": 105000,
            "phases": {k: {"label": l, "status": "todo", "notes": []} for k, l in PHASES},
            "parts": {p["id"]: {"title": p["title"], "chapters": p["chapters"], **{s: False for s in PART_STEPS}} for p in plan["parts"]},
            "baseline": {}, "words": {}, "log": []}


def render(p):
    now = sum(p["words"].values()); base = sum(p["baseline"].values()) or now
    L = ["# The Long After: expansion checklist", "",
         f"Updated {datetime.date.today()}. Words: **{now:,}** (baseline {base:,}, target about {p['target_words']:,}; "
         f"{now - base:+,} so far, {max(0, p['target_words'] - now):,} to go).", "",
         "Source of truth: `content/longafter-v2/progress.json` (this file is generated by `scripts/longafter-progress.py`).", "",
         "## Phases", ""]
    mark = {"done": "[x]", "doing": "[~]", "todo": "[ ]"}
    for k, ph in p["phases"].items():
        L.append(f"- {mark.get(ph['status'], '[ ]')} {ph['label']}")
        for n in ph["notes"][-3:]:
            L.append(f"  - {n}")
    L += ["", "## Parts", "", "| Part | Outlined | Written | Audited | Words now | Baseline | Change |", "|---|---|---|---|---|---|---|"]
    for pid, pt in p["parts"].items():
        w = sum(p["words"].get(c, 0) for c in pt["chapters"]); b = sum(p["baseline"].get(c, 0) for c in pt["chapters"])
        tick = lambda x: "yes" if x else "no"
        L.append(f"| {pid.upper()} {pt['title']} | {tick(pt['outlined'])} | {tick(pt['written'])} | {tick(pt['audited'])} | {w:,} | {b:,} | {w - b:+,} |")
    L += ["", "## What has been added or changed (newest first)", ""]
    for e in reversed(p["log"][-60:]):
        L.append(f"- {e['date']} · {e['what']}")
    L += ["", "## Still to do", ""]
    todo = [ph["label"] for ph in p["phases"].values() if ph["status"] != "done"]
    todo += [f"Part {pid.upper()} ({pt['title']}): " + ", ".join(s for s in PART_STEPS if not pt[s])
             for pid, pt in p["parts"].items() if not all(pt[s] for s in PART_STEPS)]
    L += [f"- {t}" for t in todo] or ["- nothing"]
    MD.write_text("\n".join(L) + "\n")


def main():
    a = argparse.ArgumentParser()
    a.add_argument("--baseline", action="store_true"); a.add_argument("--part"); a.add_argument("--phase")
    a.add_argument("--status"); a.add_argument("--note")
    o = a.parse_args(); p = load(); p["words"] = words()
    if o.baseline or not p["baseline"]:
        p["baseline"] = dict(p["words"])
    today = str(datetime.date.today())
    if o.part:
        p["parts"][o.part][o.status] = True
    if o.phase:
        p["phases"][o.phase]["status"] = o.status
        if o.note: p["phases"][o.phase]["notes"].append(f"{today}: {o.note}")
    if o.note:
        p["log"].append({"date": today, "what": (f"Part {o.part.upper()} {o.status}: " if o.part else "") + o.note})
    json.dump(p, open(PJ, "w"), indent=1, ensure_ascii=False)
    render(p)
    print(f"{sum(p['words'].values()):,} words; checklist at {MD.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
