#!/usr/bin/env python3
"""Names report: python3 scripts/book/taxonomy.py --book longafter  ->  <book>/TAXONOMY.md

Checks the book's names for things against the Pattern Decoder's (instruments/playbook/site: each page's <h1> and its
"Also called" names):
  links     every [text](/playbook/slug): the page exists, and the link text is the Decoder's name or one of its aliases
  glossary  every A to Z entry: matched to a Decoder name, an alias, or nothing; entries that match but carry no
            Decoder link
  bold      bolded terms in chapters (not lead-in labels) that match a Decoder alias but not its name
Read-only.
"""
import html, json, re
from common import ROOT, load, write, main_body

SITE = ROOT / "instruments/playbook/site"


def norm(s):
    s = html.unescape(s).lower().replace("’", "'")
    s = re.sub(r"\([^)]*\)", "", s)
    s = re.sub(r"[^a-z0-9 ]+", " ", s.replace("-", " "))
    s = re.sub(r"\s+", " ", s).strip()
    return re.sub(r"(ing|s)$", "", s) if len(s) > 4 else s


def decoder():
    pages, name_of = {}, {}
    for f in SITE.glob("*.html"):
        t = f.read_text(encoding="utf-8", errors="ignore")
        m = re.search(r"<h1[^>]*>([^<]+)", t)
        if not m:
            continue
        al = re.search(r'"alternateName":\s*(\[[^\]]*\])', t)
        aliases = json.loads(al.group(1)) if al else []
        pages[f.stem] = {"name": html.unescape(m.group(1)).strip(), "aliases": aliases}
        name_of.setdefault(norm(m.group(1)), ("name", f.stem))
        for x in aliases:
            name_of.setdefault(norm(x), ("alias", f.stem))
    return pages, name_of


def main():
    a, d, cfg, plan, chs = load(desc=__doc__)
    pages, name_of = decoder()
    links, missing, drift = [], [], []
    for c in chs:
        for text, slug in re.findall(r"\[([^\]]+)\]\(/playbook/([a-z0-9-]+)[^)]*\)", main_body(c["body"])):
            links.append((c["slug"], text, slug))
            if slug not in pages:
                missing.append((c["slug"], text, slug))
                continue
            p = pages[slug]
            ok = {norm(p["name"])} | {norm(x) for x in p["aliases"]}
            if norm(text) not in ok:
                drift.append((c["slug"], text, slug, p["name"]))
    gl = next((c for c in chs if c["slug"] == "a-to-z"), None)
    entries = re.findall(r"^\*\*([^*]+?)\.?\*\*\s*(.*)$", gl["body"], re.M) if gl else []
    g_rows = []
    for term, rest in entries:
        hit = name_of.get(norm(term))
        link = re.search(r"\(/playbook/([a-z0-9-]+)", rest)
        g_rows.append((term, hit, link.group(1) if link else None))
    bold_alias = []
    for c in chs:
        if c["slug"] == "a-to-z":
            continue
        for t in re.findall(r"\*\*([^*]{3,40})\*\*", main_body(c["body"])):
            if t.rstrip().endswith((".", ":", "?", "!")):
                continue
            hit = name_of.get(norm(t))
            if hit and hit[0] == "alias":
                bold_alias.append((c["slug"], t, pages[hit[1]]["name"], hit[1]))
    g_match = [r for r in g_rows if r[1]]
    g_unlinked = [r for r in g_match if not r[2]]
    g_alias = [r for r in g_match if r[1][0] == "alias"]
    g_wrong = [r for r in g_match if r[2] and r[2] != r[1][1]]
    out = [f"# Names report: {cfg['title']} against the Pattern Decoder", "",
           "Generated by `python3 scripts/book/taxonomy.py --book %s`. Read-only; no text was changed." % cfg["slug"], "",
           "## Totals", "",
           f"- Decoder pages read: {len(pages)}",
           f"- Links into the Decoder: {len(links)} ({len({l[2] for l in links})} different pages)",
           f"- Links to a Decoder page that doesn't exist: **{len(missing)}**",
           f"- Links whose text is neither the Decoder's name nor an alias: **{len(drift)}**",
           f"- A to Z entries: {len(g_rows)}; matching a Decoder name or alias: {len(g_match)}",
           f"  - matching only an alias (the Decoder calls it something else): **{len(g_alias)}**",
           f"  - matching, but with no Decoder link: **{len(g_unlinked)}**",
           f"  - linking to a different Decoder page than the name match: **{len(g_wrong)}**",
           f"- Bolded terms in chapters that use an alias instead of the Decoder's name: **{len(bold_alias)}**", "",
           "Matching ignores case, hyphens, brackets and a trailing -s/-ing. Link text that differs is not always wrong: "
           "\"children used as leverage\" reads better in a sentence than \"Children as Leverage\". The taxonomy lock "
           "(step 2.10) decides each one: the Decoder's name, with the everyday word in brackets on first mention.", ""]
    out += ["## Links to Decoder pages that don't exist", ""]
    out += [f"- {c}: [{t}](/playbook/{s})" for c, t, s in missing] or ["- none"]
    out += ["", "## Link text that differs from the Decoder's name", "", "| Chapter | Link text | Decoder page | Decoder name |",
            "|---|---|---|---|"]
    out += [f"| {c} | {t} | {s} | {n} |" for c, t, s, n in sorted(drift, key=lambda x: x[2])]
    out += ["", "## A to Z entries against the Decoder", "", "| Entry | Decoder match | Linked to |", "|---|---|---|"]
    for term, hit, link in g_rows:
        m = f"{hit[0]}: {pages[hit[1]]['name']} ({hit[1]})" if hit else "-"
        flag = " **no link**" if hit and not link else (" **different page**" if hit and link and link != hit[1] else "")
        out.append(f"| {term} | {m} | {link or '-'}{flag} |")
    out += ["", "## Bolded terms using an alias", ""]
    out += [f"- {c}: **{t}** (Decoder: {n}, /playbook/{s})" for c, t, n, s in bold_alias] or ["- none"]
    write(a, d, "TAXONOMY.md", "\n".join(out) + "\n")


if __name__ == "__main__":
    main()
