#!/usr/bin/env python3
"""Arc report: python3 scripts/book/meso.py --book longafter  ->  <book>/MESO.md

  seams     the last paragraph of chapter N beside the first paragraph of N+1, so dead ends and jolts show
  shapes    a first guess at each chapter's opening shape (scenario, question, myth, tool, explainer) and the runs of
            three or more alike; the guess is a heuristic for a human to correct, never a verdict
  concepts  each concept in book.json: the chapters that explain it (a defining sentence) and those that only mention it
Read-only.
"""
import re
from common import load, write, main_body, blocks, plain

MYTH = re.compile(r"\b(people (say|tell|think|assume)|you may have heard|it'?s often said|myth|the common (idea|belief)|"
                  r"you'?ve probably been told|everyone says)\b", re.I)
SCEN = re.compile(r"^(If you|When you|You |Maybe you|Perhaps you|It'?s |Some(one|times)|A message|The message|"
                  r"Your phone|They )", re.I)


def shape(c, bl):
    if c["part"] == "tools":
        return "tool"
    first = next((t for k, t in bl if k != "heading"), "")
    p = plain(first)
    head_before = bl and bl[0][0] == "heading"
    if MYTH.search(p):
        return "myth"
    if head_before or re.search(r"\?\s*$", p.split("\n")[0]) or p.split(". ")[0].rstrip().endswith("?"):
        return "question"
    two = re.split(r"(?<=[.!?])\s+", p)[:3]
    if SCEN.match(p) or '"' in p[:200] or "“" in p[:200] or any(re.match(r"(You|Your)\b", s) for s in two[1:]):
        return "scenario"
    return "explainer"


DEF = r"(?:\bis\b|\bare\b|\bmeans\b|\brefers to\b|\bdescribes\b|\bis when\b|\bis what\b|\b(?:is|are) called\b|\bstands for\b)"


REFERENCE = set()  # glossary and summary pages repeat definitions by design; set from book.json


def concept_use(chs, terms):
    defines, mentions, sections = [], [], []
    for c in chs:
        if c["slug"] in REFERENCE:
            continue
        body = main_body(c["body"])
        sents = re.split(r"(?<=[.!?])\s+", plain(body))
        heads = " ".join(re.findall(r"^#+ .*$", body, re.M)).lower() + " " + c["title"].lower()
        if any(t in heads for t in terms):
            sections.append(c["slug"])
        if not any(t in body.lower() for t in terms):
            continue
        defined = any(
            re.search(r"^(?:\W*\w+\W+){0,4}?(?:%s)\W{0,3}\s*%s" % ("|".join(map(re.escape, terms)), DEF), s, re.I)
            or re.search(r"(?:called|known as|name for this is)\s+\W?(?:%s)" % "|".join(map(re.escape, terms)), s, re.I)
            for s in sents)
        (defines if defined else mentions).append(c["slug"])
    return defines, mentions, sections


def main():
    a, d, cfg, plan, chs = load(desc=__doc__)
    REFERENCE.update(cfg.get("reference_pages", []))
    parts = {p["id"]: p["title"] for p in plan["parts"]}
    info = []
    for c in chs:
        bl = blocks(main_body(c["body"]))
        body_bl = [t for k, t in bl if k != "heading"]
        info.append(dict(c=c, shape=shape(c, bl), first=plain(body_bl[0]) if body_bl else "",
                         last=plain(body_bl[-1]) if body_bl else "", handoff="(ch:" in (body_bl[-1] if body_bl else "")))
    # runs of three or more alike within the reading order (tools excluded)
    runs, cur = [], []
    seq = [i for i in info if i["c"]["part"] not in ("tools", "start")]
    for i in seq:
        if cur and cur[-1]["shape"] == i["shape"]:
            cur.append(i)
        else:
            if len(cur) >= 3:
                runs.append(cur)
            cur = [i]
    if len(cur) >= 3:
        runs.append(cur)
    from collections import Counter
    sc = Counter(i["shape"] for i in seq)
    out = [f"# Meso (arc) report: {cfg['title']}", "",
           "Generated by `python3 scripts/book/meso.py --book %s`. Read-only; no text was changed." % cfg["slug"], "",
           "## Totals", "",
           f"- Chapters in the reading order (Start and Toolbox excluded): {len(seq)}",
           "- Opening shapes (first guess): " + ", ".join(f"{k} {v}" for k, v in sc.most_common()),
           f"- Runs of three or more chapters opening the same way: **{len(runs)}** "
           f"(chapters inside them: {sum(len(r) for r in runs)})",
           f"- Chapters that end without a link onward: **{sum(not i['handoff'] for i in info)}/{len(info)}**", ""]
    rows = []
    for name, terms in cfg["concepts"].items():
        de, me, se = concept_use(chs, [t.lower() for t in terms])
        rows.append((name, de, me, se))
    multi = [r for r in rows if len(set(r[1]) | set(r[3])) > 1]
    out += [f"- Concepts defined or given a section in more than one chapter: **{len(multi)}/{len(rows)}**", "",
            "## Part order", "",
            "The order the reader meets the parts. The plan's target arc is Stabilise, Recognise, Defend, Rebuild.", ""]
    out += [f"{n}. {p['title']} ({len(p['chapters'])} chapters)" for n, p in enumerate(plan["parts"], 1)]
    out += ["", "## Opening shapes, in reading order", "",
            "Heuristic: scenario = opens on a situation or a quote; question = opens on a question or straight into a "
            "question heading; myth = opens on what people say; explainer = anything else. Correct by hand.", "",
            "| # | Part | Chapter | Shape |", "|---:|---|---|---|"]
    for n, i in enumerate(seq, 1):
        out.append(f"| {n} | {parts[i['c']['part']]} | {i['c']['slug']} | {i['shape']} |")
    out += ["", "## Runs of three or more alike", ""]
    out += [f"- **{r[0]['shape']}** x{len(r)}: " + ", ".join(i["c"]["slug"] for i in r) for r in runs] or ["- none"]
    out += ["", "## Concepts explained in more than one place", "",
            "\"Explains\" = a sentence that defines the term (\"X is…\", \"called X\"). The target is one full explanation "
            "and links everywhere else. Reference pages (%s) are left out: they repeat definitions by design." % ", ".join(sorted(REFERENCE)), "", "| Concept | Defined in | Has a section or title on it | Mentioned only in |", "|---|---|---|---:|"]
    for name, de, me, se in sorted(rows, key=lambda r: -(len(r[1]) + len(r[3]))):
        out.append(f"| {name} | {len(de)}: {', '.join(de) or '-'} | {len(se)}: {', '.join(se) or '-'} | {len(me)} |")
    out += ["", "## Seams: how each chapter ends and the next begins", "",
            "Read down these pairs. A good seam hands the reader on; a dead end stops them.", ""]
    for x, y in zip(info, info[1:]):
        mark = "" if x["handoff"] else " (no onward link)"
        out += [f"### {x['c']['slug']} → {y['c']['slug']}{mark}", "",
                f"> **ends:** …{x['last'][-300:]}", ">", f"> **next opens:** {y['first'][:300]}…", ""]
    write(a, d, "MESO.md", "\n".join(out) + "\n")


if __name__ == "__main__":
    main()
