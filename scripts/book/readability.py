#!/usr/bin/env python3
"""2am readability report: python3 scripts/book/readability.py --book longafter  ->  <book>/READABILITY.md

Per chapter (Sources excluded):
  paragraphs   prose paragraphs over para_warn words (warn) and para_fail words (fail)
  anchors      longest run of plain prose with no heading, list, quote, table or bold lead-in; runs over anchor_every
  grade        Flesch-Kincaid grade against the chapter's class (crisis = heavy chapters, legal parts, default)
  jurisdiction paragraphs with legal or medical words that name no place and point to no "where you live" route
  handoff      the last block before Sources links on to another chapter
Read-only. Exit 0 always: this is a report, not a gate (the gate comes once the numbers are agreed).
"""
import re, sys
from common import load, write, main_body, blocks, words, grade, chapter_class

# A claim about how the law or a system works: the words that change meaning from one country to the next.
LEGAL = re.compile(r"\b(custody|injunction|protective orders?|protection orders?|restraining orders?|non-molestation|"
                   r"legal aid|offen[cs]es?|a crime|criminal offen\w+|illegal|unlawful|against the law|the law (says|allows|"
                   r"requires|lets)|statute|admissible|entitled to|court (can|will|may|must|usually|often)|"
                   r"(police|courts?|judges?) (can|cannot|can't|must|will|may) )", re.I)
PLACE = re.compile(r"\b(UK|England|Wales|Scotland|Northern Ireland|Ireland|Irish|US|USA|United States|American|"
                   r"Canada|Canadian|Australia|Australian|New Zealand|state|states|province|territor\w+|countr\w+|"
                   r"where you live|your area|in some places|in many places|some places|many places|local|"
                   r"jurisdiction|varies|vary|differ|everywhere|anywhere|most places)\b|ch:find-help|ch:where-to-find-the-right-body|ch:if-youre-not-safe",
                   re.I)


def audit(c, cfg):
    g = cfg["gate"]
    body = main_body(c["body"])
    bl = blocks(body)
    long_w, long_f, juris = [], [], []
    run = worst = 0
    over = 0
    for kind, t in bl:
        n = len(words(t))
        if kind == "para":
            if n > g["para_fail"]:
                long_f.append(n)
            elif n > g["para_warn"]:
                long_w.append(n)
            run += n
            worst = max(worst, run)
        else:
            if run > g["anchor_every"]:
                over += 1
            run = 0
        m = LEGAL.search(t) if kind in ("para", "label", "list") else None
        if m and not PLACE.search(t):
            flat = re.sub(r"\s+", " ", t)
            i = max(0, flat.lower().find(m.group(0).lower()) - 50)
            juris.append(("…" if i else "") + flat[i:i + 130])
    if run > g["anchor_every"]:
        over += 1
    cls = chapter_class(c, cfg)
    gr = grade("\n".join(t for k, t in bl if k != "heading"))
    last = next((t for k, t in reversed(bl) if k != "heading"), "")
    handoff = "(ch:" in last
    return dict(slug=c["slug"], part=c["part"], cls=cls, words=len(words(body)), grade=round(gr, 1),
                gmax=g["grade_max"][cls], warn=long_w, fail=long_f, worst=worst, over=over, juris=juris,
                handoff=handoff, last=re.sub(r"\s+", " ", last)[-120:])


def main():
    a, d, cfg, plan, chs = load(desc=__doc__)
    rows = [audit(c, cfg) for c in chs if c["part"] != "start" or c["slug"] != "where-are-you-right-now"]
    g = cfg["gate"]
    grade_bad = [r for r in rows if r["grade"] > r["gmax"]]
    tot = lambda k: sum(len(r[k]) for r in rows)
    out = [f"# Readability report: {cfg['title']}", "",
           "Generated by `python3 scripts/book/readability.py --book %s`. Read-only; no text was changed." % cfg["slug"], "",
           "## Totals", "",
           f"- Chapters checked: {len(rows)} ({sum(r['words'] for r in rows):,} words, Sources excluded)",
           f"- Paragraphs over {g['para_fail']} words (fail): **{tot('fail')}** in {sum(1 for r in rows if r['fail'])} chapters",
           f"- Paragraphs {g['para_warn']+1}-{g['para_fail']} words (warn): **{tot('warn')}** in {sum(1 for r in rows if r['warn'])} chapters",
           f"- Prose runs over {g['anchor_every']} words with no anchor: **{sum(r['over'] for r in rows)}** in {sum(1 for r in rows if r['over'])} chapters",
           f"- Chapters over their reading-grade limit: **{len(grade_bad)}** "
           f"(crisis {sum(1 for r in grade_bad if r['cls']=='crisis')}/{sum(1 for r in rows if r['cls']=='crisis')}, "
           f"legal {sum(1 for r in grade_bad if r['cls']=='legal')}/{sum(1 for r in rows if r['cls']=='legal')}, "
           f"other {sum(1 for r in grade_bad if r['cls']=='default')}/{sum(1 for r in rows if r['cls']=='default')})",
           f"- Legal claims naming no place: **{tot('juris')}** in {sum(1 for r in rows if r['juris'])} chapters",
           f"- Chapters whose last block hands off to another chapter: **{sum(r['handoff'] for r in rows)}/{len(rows)}**",
           "", "Grade limits: crisis (heavy) chapters %(crisis)s, legal (Part V) %(legal)s, everything else %(default)s. "
           "Flesch-Kincaid is a rough guide; short sentences and plain words move it, jargon that must stay does not." % g["grade_max"],
           "", "## Per chapter", "",
           "| Chapter | Class | Words | Grade (max) | Paras >90 | Paras 61-90 | Longest unanchored run | Place-less legal claims | Handoff |",
           "|---|---|---:|---:|---:|---:|---:|---:|:-:|"]
    for r in rows:
        flag = " **over**" if r["grade"] > r["gmax"] else ""
        out.append(f"| {r['slug']} | {r['cls']} | {r['words']} | {r['grade']} ({r['gmax']}){flag} | {len(r['fail'])} | "
                   f"{len(r['warn'])} | {r['worst']} | {len(r['juris'])} | {'yes' if r['handoff'] else 'no'} |")
    out += ["", "## Paragraphs to split (over %d words)" % g["para_fail"], ""]
    out += [f"- {r['slug']}: {', '.join(map(str, r['fail']))} words" for r in rows if r["fail"]] or ["- none"]
    out += ["", "## Legal claims that name no place", "",
            "Each needs a place (\"in England and Wales\", \"in most US states\") or a pointer to the country routes.", ""]
    for r in rows:
        for j in r["juris"]:
            out.append(f"- **{r['slug']}**: {j}…")
    out += ["", "## Chapters that end without a handoff", "", "The last thing before Sources, as it stands:", ""]
    out += [f"- **{r['slug']}**: …{r['last']}" for r in rows if not r["handoff"]] or ["- none"]
    write(a, d, "READABILITY.md", "\n".join(out) + "\n")


if __name__ == "__main__":
    main()
