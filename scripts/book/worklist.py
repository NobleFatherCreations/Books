#!/usr/bin/env python3
"""Per-chapter fix list for the step 2 writing pass, built from the step 1 reports' checks.

  python3 scripts/book/worklist.py --book longafter            -> <book>/WORKLIST.md
Each chapter lists only what applies to it: long paragraphs, place-less legal claims, missing handoff, missing
closing step, opening shape to change (to break a run of three), concepts it must define or only link to, Decoder
name drift, and whether it gets a dialogue decoder or a sister-book bridge (from book.json "step2").
"""
import re, sys
sys.argv = [a for a in sys.argv]
from common import load, write, main_body, blocks, words, grade, chapter_class
import importlib.util
from pathlib import Path

H = Path(__file__).resolve().parent


def mod(name):
    s = importlib.util.spec_from_file_location(name, H / f"{name}.py")
    m = importlib.util.module_from_spec(s); s.loader.exec_module(m); return m


R, M, T = mod("readability"), mod("meso"), mod("taxonomy")


def main():
    a, d, cfg, plan, chs = load(desc=__doc__)
    s2 = cfg.get("step2", {})
    M.REFERENCE.update(cfg.get("reference_pages", []))
    homes = s2.get("concept_homes", {})
    # shape runs -> chapters that must change opening shape (every third in a run)
    seq = [c for c in chs if c["part"] not in ("tools", "start")]
    shapes = {c["slug"]: M.shape(c, blocks(main_body(c["body"]))) for c in seq}
    change, run = set(), []
    for c in seq:
        if run and shapes[run[-1]] == shapes[c["slug"]]:
            run.append(c["slug"])
        else:
            run = [c["slug"]]
        if len(run) >= 3 and len(run) % 3 == 0:
            change.add(c["slug"])
    pages, name_of = T.decoder()
    out = ["# Step 2 worklist: %s" % cfg["title"], "",
           "Generated by `python3 scripts/book/worklist.py`. The brief is `V6-WRITING-BRIEF.md`; this is what each chapter "
           "needs on top of the voice pass.", ""]
    for c in chs:
        r = R.audit(c, cfg)
        body = main_body(c["body"])
        items = []
        if r["fail"] or r["warn"]:
            items.append(f"split paragraphs over 60 words ({len(r['fail'])} over 90, {len(r['warn'])} at 61-90)")
        if r["over"]:
            items.append(f"break up the prose run of {r['worst']} words with a heading, list or block")
        if r["grade"] > r["gmax"]:
            items.append(f"reading grade {r['grade']} > {r['gmax']} ({r['cls']}): shorter sentences, plainer words")
        for j in r["juris"]:
            items.append(f"say where this applies: {j}")
        if c["part"] not in ("tools",) and not r["handoff"]:
            items.append("end with a handoff line: one sentence pointing to the chapter that naturally comes next, as a ch: link, inside or after the closing step")
        if c["part"] not in ("start", "tools") and "::: action" not in c["body"]:
            items.append("add a closing ::: action block: one physical step, 3 minutes or less")
        if c["slug"] in change:
            items.append(f"change the opening shape (currently {shapes[c['slug']]}, third in a row): open with a question or a myth instead")
        for concept, home in homes.items():
            terms = cfg["concepts"].get(concept, [concept])
            de, me, se = M.concept_use([c], [t.lower() for t in terms])
            if c["slug"] == home:
                items.append(f"HOME of '{concept}': give it one full plain definition (40-60 words) straight under a question heading (\"## What is {concept}?\" or close)")
            elif de or se:
                items.append(f"'{concept}' is explained here but its home is ch:{home}: cut to one line plus a link there")
        for text, slug in re.findall(r"\[([^\]]+)\]\(/playbook/([a-z0-9-]+)[^)]*\)", body):
            p = pages.get(slug)
            if p and T.norm(text) not in {T.norm(p["name"])} | {T.norm(x) for x in p["aliases"]}:
                items.append(f"Decoder link text '{text}': use the Decoder's name '{p['name']}' (everyday word in brackets if it reads better)")
        if c["slug"] in s2.get("decoder_dialogue", []):
            items.append("add one ::: decoder block (They say / What it's doing / A reply you could send), linked to the Decoder page")
        for book, why in s2.get("bridges", {}).get(c["slug"], {}).items():
            items.append(f"add a ::: bridge {book} block: {why}")
        out += [f"## {c['slug']} ({c['file']}, {r['cls']}, {r['words']} words)", ""]
        out += [f"- [ ] {x}" for x in items] or ["- [ ] voice pass only"]
        out.append("")
    write(a, d, "WORKLIST.md", "\n".join(out) + "\n")


if __name__ == "__main__":
    main()
