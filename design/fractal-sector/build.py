#!/usr/bin/env python3
"""Fractal² sector site generator.  python3 design/fractal-sector/build.py ent [--target preview|production] [--base /fractal2]

Reads   content/fractal/<s>/build/{sector,links,derived}.json (ingest.py + derive.py), content/fractal/<s>/nav.json,
        content/fractal2/sectors.json (base path + registry), design/fractal2/tokens.css + fonts/, strings.json
Writes  library/fractal2/site/<base>/<slug>.html and <base>/<slug>/**   (sector pages; flat .html, served extensionless)
        library/fractal2/site/<base>/_a/f/  (fonts + licences)   <base>/_a/d/<s>-search.json
        library/fractal2/manifests/<s>.json, library/fractal2/redirects/*, library/fractal2/build/<s>/og-src/
The publish dir library/fractal2/site/ is shared with the intro: only this sector's own outputs are cleaned.

Modules: lib.py (config, context, markdown), frame.py (frame, switcher, search), pages_index.py, pages_combo.py,
pages_tactic.py. Words are the author's; this only lays them out.
"""
import json
import shutil
import sys

from lib import CONFIG, RESERVED, S, Ctx, clip, fam_name, first_sentence
from pages_combo import combo_page
from pages_index import az_page, family_page, home, method_page, patterns_page, start_page, tactics_page, take_page
from pages_paths import in_it_now_page, map_page, notice_page, sign_page, worried_page
from pages_tactic import stage_page, tactic_page


def search_index(cx):
    out = []
    for c in cx.d["combos"]:
        if c["combo_id"] in cx.live:
            out.append({"t": "p", "n": c["name"], "u": cx.combo_url(c["combo_id"]), "s": fam_name(cx.cats[c["category_id"]]),
                        "d": clip(first_sentence(c["definition"]), 140), "a": []})
    for t in cx.d["tactics"]:
        aka = [x.strip() for x in t.get("also_called", "").replace(";", ",").split(",") if x.strip()]
        out.append({"t": "t", "n": t["name"], "u": cx.tactic_url(t["single_no"]), "s": cx.stage_name(t["stage"]),
                    "d": clip(first_sentence(t["definition"]), 140), "a": aka})
    return out


def og_cards(cx, outdir):
    """HTML for social cards; og.mjs screenshots them at 1200x630."""
    cards = {"home": (S("site"), cx.title, "%d tactics · %d patterns" % (len(cx.d["tactics"]), len(cx.live)), 1)}
    for i, s in enumerate(cx.d["stages"]):
        cards["stage-" + s.lower()] = (S("stage_of", n=i + 1), cx.stage_name(s), cx.short, i + 1)
    for c in cx.d["categories"]:
        cards["family-" + c["slug"]] = (cx.short, fam_name(c), S("site"), 1)
    if outdir.exists():
        shutil.rmtree(outdir)
    outdir.mkdir(parents=True)
    from frame import css
    style = css(cx).replace(cx.root + "/_a/f/", str(CONFIG["fonts"]) + "/")
    for name, (k, h, s, col) in cards.items():
        (outdir / (name + ".html")).write_text(
            '<!DOCTYPE html><html><head><meta charset="utf-8"><style>%s</style></head><body class="ogb">'
            '<div class="og" style="--c:var(--s%d)"><p class="kicker">%s</p><h1>%s</h1><p class="ogs">%s</p>'
            '<p class="ogf">noblefathercreations.com%s</p></div></body></html>' % (style, col, k, h, s, cx.base))
    return list(cards)


def sitemap(urls):
    return ('<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' +
            "".join("<url><loc>%s</loc></url>\n" % (CONFIG["origin"] + u) for u in urls) + "</urlset>\n")


def redirects(cx, pages):
    """Old prototype (/fractal/<slug>/... on its own Netlify site) -> the new address, 301. Never edits hub/."""
    from lib import ROOT
    old_dir = ROOT / "library/fractal/sectors" / cx.sector / "site/fractal" / cx.slug
    O = CONFIG["origin"]
    old_base = "/fractal/" + cx.slug
    lines = ["# Old prototype site -> Fractal² (generated by design/fractal-sector/build.py; do not edit by hand)",
             "/  %s%s  301!" % (O, cx.base), "%s  %s%s  301!" % (old_base, O, cx.base)]
    special = {"standards": "method#standards"}
    olds = sorted(p.stem for p in old_dir.glob("*.html")) if old_dir.exists() else []
    missing = []
    for o in olds:
        new = special.get(o, o)
        if new.split("#")[0] not in pages:
            missing.append(o)
            new = ""
        lines.append("%s/%s  %s%s  301!" % (old_base, o, O, cx.u(new)))
    lines.append("%s/*  %s%s/:splat  301!" % (old_base, O, cx.base))
    site_rules = ["# Inside the Fractal² site (merge into the publish dir's _redirects; this generator does not own that file)",
                  "%s  %s  301!" % (cx.u("stage-extract"), cx.u("stage-control")),
                  "%s  %s  301!" % (cx.u("standards"), cx.u("method") + "#standards")]
    hub = ["# Lines the hub (hub/catalogue-redesign._redirects) would need. Not applied: hub/ is not edited by this generator.",
           "# Place above the hub's existing /fractal/* rule.",
           "%s  %s  301!" % (old_base, cx.base), "%s/standards  %s#standards  301!" % (old_base, cx.u("method")),
           "%s/*  %s/:splat  301!" % (old_base, cx.base),
           "# Plus the proxy rules for %s/* once the Fractal² site's Netlify address is chosen (directing session decides)." % cx.root]
    return "\n".join(lines) + "\n", "\n".join(site_rules) + "\n", "\n".join(hub) + "\n", missing


def main(sector, target, base):
    cx = Ctx(sector, target, base)
    for c in cx.d["combos"]:
        assert c["slug"] not in RESERVED and not c["slug"].startswith(("stage-", "family-")), "combo slug collides with a reserved name: " + c["slug"]
    pub = CONFIG["publish"]
    rootdir = pub / cx.root.strip("/")
    sector_dir = rootdir / cx.slug
    # clean only what this generator owns for this sector
    if sector_dir.exists():
        shutil.rmtree(sector_dir)
    for f in (rootdir / (cx.slug + ".html"), rootdir / "_a/d" / (sector + "-search.json")):
        if f.exists():
            f.unlink()
    (sector_dir / "tactic").mkdir(parents=True)

    pages = {"": home(cx), "start": start_page(cx), "patterns": patterns_page(cx), "tactics": tactics_page(cx),
             "method": method_page(cx), "take-it-with-you": take_page(cx), "a-z": az_page(cx),
             "notice": notice_page(cx), "in-it-now": in_it_now_page(cx), "worried-about-someone": worried_page(cx),
             "before-you-sign": sign_page(cx), "map": map_page(cx)}
    groups = {"core": list(pages)}
    for s in cx.d["stages"]:
        pages["stage-" + s.lower()] = stage_page(cx, s)
    for i, cat in enumerate(cx.d["categories"]):
        pages["family-" + cat["slug"]] = family_page(cx, cat, i)
    for t in cx.d["tactics"]:
        pages["tactic/" + t["slug"]] = tactic_page(cx, t)
    for c in cx.d["combos"]:
        if c["combo_id"] in cx.live:
            pages[c["slug"]] = combo_page(cx, c)
    groups.update({"stages": ["stage-" + s.lower() for s in cx.d["stages"]],
                   "families": ["family-" + c["slug"] for c in cx.d["categories"]],
                   "tactics": ["tactic/" + t["slug"] for t in cx.d["tactics"]],
                   "combos": [cx.combos[k]["slug"] for k in cx.combos if k in cx.live]})
    for p, h in pages.items():
        assert "{{" not in h, "unfilled template in " + p
        (rootdir / (cx.slug + ".html") if p == "" else sector_dir / (p + ".html")).write_text(h)

    fdir = rootdir / "_a/f"
    fdir.mkdir(parents=True, exist_ok=True)
    for f in CONFIG["fonts"].iterdir():
        if f.suffix in (".woff2", ".txt"):
            shutil.copy2(f, fdir / f.name)
    ddir = rootdir / "_a/d"
    ddir.mkdir(parents=True, exist_ok=True)
    idx = json.dumps(search_index(cx), ensure_ascii=False, separators=(",", ":"))
    (ddir / (sector + "-search.json")).write_text(idx)
    from lib import ROOT
    (ROOT / "content/fractal" / sector / "build" / (sector + "-search.json")).write_text(idx)

    urls = [cx.u(p) for p in pages]
    (sector_dir / "sitemap.xml").write_text(sitemap(urls))
    work = CONFIG["work"]
    og = og_cards(cx, work / "build" / sector / "og-src")
    (work / "redirects").mkdir(parents=True, exist_ok=True)
    old, site_rules, hub, missing = redirects(cx, pages)
    (work / "redirects/old-prototype._redirects").write_text(old)
    (work / "redirects" / (sector + "-site._redirects")).write_text(site_rules)
    (work / "redirects/HUB-RULES.txt").write_text(hub)
    (work / "manifests").mkdir(parents=True, exist_ok=True)
    (work / "manifests" / (sector + ".json")).write_text(json.dumps({
        "sector": cx.d["sector"], "slug": cx.slug, "target": target, "root": cx.root, "base": cx.base, "built": cx.date,
        "version": cx.version, "pages": len(pages), "combos_live": len(cx.live), "combos_held": len(cx.combos) - len(cx.live),
        "og": og, "og_src": str((work / "build" / sector / "og-src").relative_to(ROOT)),
        "groups": groups, "reserved": RESERVED,
        "expect": {c["slug"]: {"words": c["reader_words"] + cx.res_delta.get(c["combo_id"], 0), "safety": c["has_safety_note"]}
                   for c in cx.d["combos"] if c["combo_id"] in cx.live}}, indent=1))
    print("built %d pages (%d combos live, %d held back) -> %s" % (len(pages), len(cx.live), len(cx.combos) - len(cx.live), sector_dir))
    if missing:
        print("old prototype pages with no new counterpart (sent to the sector home):", ", ".join(missing))
    print("hub rules needed: library/fractal2/redirects/HUB-RULES.txt")


if __name__ == "__main__":
    a = sys.argv[1:]
    tgt = a[a.index("--target") + 1] if "--target" in a else "preview"
    base = a[a.index("--base") + 1] if "--base" in a else None
    main(a[0] if a and not a[0].startswith("--") else "ent", tgt, base)
